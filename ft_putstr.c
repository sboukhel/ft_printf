#include "printf.h"

int	ft_putstr(char *s)
{
	int	i;

	if (!s || s[0] == '\0'){
		return (ft_putstr("null"));
	}
	i = 0;
	while (s[i])
	{
		write(1, &s[i], 1);
		i++;
	}
	return (ft_strlen(s));
}
